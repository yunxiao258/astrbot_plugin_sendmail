def render_text(text: str, placeholders: list, values: dict) -> str:
    """按占位符白名单替换文本中的 {占位符}。

    仅替换 placeholders 中声明的占位符（str.replace 实现，不做任何
    格式化解析），其余键值一律忽略，防 format 注入；缺失的占位符替换为空字符串。
    """
    out = str(text)
    for ph in placeholders or []:
        out = out.replace("{" + str(ph) + "}", str(values.get(ph, "")))
    return out


def render_template(tpl: dict, values: dict) -> tuple[str, str]:
    """渲染模板的主题与正文，返回 (subject, body)"""
    placeholders = tpl.get("placeholders") or []
    subject = render_text(str(tpl.get("subject") or ""), placeholders, values)
    body = render_text(str(tpl.get("body") or ""), placeholders, values)
    return subject, body
